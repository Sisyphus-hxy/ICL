"""Unified batched GPU policy server for non-default demo (demo-swap) closed-loop
LIBERO-Gen Goal Chain evaluation.

Supports all trained models under the exact same server & deterministic DDIM seeding:
  - bpp_rgb_only       (E5Policy, use_residual=False)
  - e5                 (E5Policy, use_residual=True)
  - bpp_full           (BPPFullPolicy, RGB + 11D proprio + 20-step prompt actions)
  - e6_stage2          (Stage2LatentTransferPolicy, apply_delta=True)
  - e6_stage2_no_delta (Stage2LatentTransferPolicy, apply_delta=False)

Prompt modes:
  - shifted   : same-task disjoint demos `demo_{10 + di}` (demo_10..demo_19) from unseen HDF5
  - oracle_gt : same-layout GT demo generated by `bpp/experiments/oracle_gt` (keyed by (ti, qi))
  - shuffle   : wrong-task demo from task `(ti + 1) % 10` (`demo_0..demo_9`)
"""

from __future__ import annotations

import argparse
import os
import queue
import signal
import socket
import threading
import time
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import h5py
import numpy as np
import torch
from scipy.spatial.transform import Rotation

from e5 import (
    ACTION_DIM_10D,
    ACTION_HORIZON,
    BPP_CKPT,
    DEMO_STRIDE,
    EMBED_DIM,
    EXEC_HORIZON,
    ROOT,
)
from e5.actions import action_7d_to_10d, extract_exec_actions
from e5.bpp_full import BPPFullPolicy, FULL_QUERY_TOKENS
from e5.model import E5Policy
from e5.policy_server import (
    CHAIN_HDF5_DIR,
    DEFAULT_PROMPT_SLOTS,
    PROPRIO_BYTES,
    PROPRIO_SHAPE,
    REQ_HDR,
    REQ_TOTAL_BYTES,
    RGB_BYTES,
    RGB_SHAPE,
    _recv_exact,
    get_chain_tasks,
)
from e5.vision import BPPVisualEncoder

from .stage2_1_model import load_stage2_1_policy
from .stage2_model import DEFAULT_STAGE1_CKPT, load_stage2_policy

ORACLE_GT_EXPERTS_DIR = (
    ROOT / "bpp/experiments/oracle_gt/outputs/liberogen_goal_chain/experts"
)
SHIFT_OFFSET = 10


class DemoSwapBatchedEngine:
    """Pre-encodes non-default Chain prompts once on GPU and serves batched closed-loop inference."""

    def __init__(
        self,
        *,
        mode: str,
        prompt_mode: str,
        checkpoint: Path,
        stage1_ckpt: Optional[Path],
        device: torch.device,
        use_bf16: bool = True,
        delta_steps: Optional[int] = None,
        delta_scale: float = 1.0,
        tasks: Optional[List[str]] = None,
    ):
        if mode not in (
            "bpp_rgb_only",
            "e5",
            "bpp_full",
            "e6_stage2",
            "e6_stage2_no_delta",
            "e6_stage2_1",
            "e6_stage2_1_no_delta",
            "e6_stage2_1_2step",
        ):
            raise ValueError(f"Unsupported mode: {mode}")
        if prompt_mode not in ("default_paired", "shifted", "oracle_gt", "shuffle"):
            raise ValueError(f"Unsupported prompt_mode: {prompt_mode}")

        self.mode = mode
        self.prompt_mode = prompt_mode
        self.apply_delta = mode in ("e6_stage2", "e6_stage2_1", "e6_stage2_1_2step")
        self.is_stage2_1 = mode in ("e6_stage2_1", "e6_stage2_1_no_delta", "e6_stage2_1_2step")
        self.num_delta_steps = (
            int(delta_steps)
            if delta_steps is not None
            else (2 if mode == "e6_stage2_1_2step" else (1 if self.apply_delta else 0))
        )
        self.delta_scale = float(delta_scale)
        self.device = device
        self.use_bf16 = use_bf16 and (device.type == "cuda")
        self.tasks = tasks if tasks is not None else get_chain_tasks()

        t0 = time.monotonic()
        self.visual = BPPVisualEncoder(ckpt_path=BPP_CKPT, load_weights=True).to(device).eval()

        if mode in ("e5", "bpp_rgb_only"):
            ck = torch.load(checkpoint, map_location="cpu", weights_only=False)
            self.policy = E5Policy(
                use_residual=(mode == "e5"),
                load_pretrained_reader=False,
            )
            self.policy.load_state_dict(ck["model"], strict=True)
            self.policy = self.policy.to(device).eval()
            self.ckpt_epoch = ck.get("epoch")
        elif mode == "bpp_full":
            ck = torch.load(checkpoint, map_location="cpu", weights_only=False)
            self.policy = BPPFullPolicy(load_pretrained_reader=False)
            self.policy.load_state_dict(ck["model"], strict=True)
            self.policy = self.policy.to(device).eval()
            self.ckpt_epoch = ck.get("epoch")
        elif self.is_stage2_1:
            self.policy, payload = load_stage2_1_policy(
                checkpoint, stage1_ckpt=stage1_ckpt, device=device
            )
            self.ckpt_epoch = payload.get("epoch")
        else:
            self.policy, payload = load_stage2_policy(
                checkpoint, stage1_ckpt=stage1_ckpt, device=device
            )
            self.ckpt_epoch = payload.get("epoch")

        self.prompt_memories: Dict[Tuple[int, int], torch.Tensor] = {}
        self._preencode_all_prompts()
        print(
            f"[DemoSwapServer] Ready: mode={mode} prompt_mode={prompt_mode} "
            f"delta_steps={self.num_delta_steps} delta_scale={self.delta_scale} "
            f"ckpt={checkpoint} ep={self.ckpt_epoch} prompts={len(self.prompt_memories)} "
            f"device={device} bf16={self.use_bf16} startup={time.monotonic() - t0:.1f}s",
            flush=True,
        )

    def _encode_single_demo_group(
        self,
        d: h5py.Group,
        conv: str,
        amp_ctx,
    ) -> torch.Tensor:
        av_1hz = d["obs/agentview_rgb"][::DEMO_STRIDE]
        eh_1hz = d["obs/eye_in_hand_rgb"][::DEMO_STRIDE]
        P = len(av_1hz)
        demo_rgb = self.visual.encode_dual_camera_uint8(
            av_1hz,
            eh_1hz,
            convention=conv,
            batch_size=256,
            autocast_dtype=torch.float16 if self.device.type == "cuda" else None,
        )  # (P, 2, 768) float32 on GPU

        with amp_ctx:
            if self.mode in ("e5", "bpp_rgb_only"):
                assert isinstance(self.policy, E5Policy)
                rr = self.policy.reference_reader
                max_p = rr.prompt_pos_emb.shape[1]
                if P > max_p:
                    demo_rgb = demo_rgb[:max_p]
                    P = max_p
                M_d = self.policy.prompt_pooler(demo_rgb[None])  # (1, P, 768)
                mem = M_d + rr.prompt_pos_emb[:, :P, :]
                if rr.attention_sink_tokens is not None:
                    mem = torch.cat([rr.attention_sink_tokens, mem], dim=1)
            elif self.mode == "bpp_full":
                assert isinstance(self.policy, BPPFullPolicy)
                max_p = self.policy.prompt_pos_emb.shape[1]
                if P > max_p:
                    demo_rgb = demo_rgb[:max_p]
                    P = max_p
                ee_pos = d["obs/ee_pos"][::DEMO_STRIDE][:P].astype(np.float32)
                ee_ori_rv = d["obs/ee_ori"][::DEMO_STRIDE][:P].astype(np.float32)
                ee_ori = (
                    Rotation.from_rotvec(ee_ori_rv)
                    .as_matrix()[:, :2, :]
                    .reshape(-1, 6)
                    .astype(np.float32)
                )
                grip = d["obs/gripper_states"][::DEMO_STRIDE][:P].astype(np.float32)
                demo_prop = torch.from_numpy(
                    np.concatenate([ee_pos, ee_ori, grip], axis=-1)
                ).to(device=self.device, dtype=torch.float32)[None]

                acts_10d = action_7d_to_10d(d["actions"][:].astype(np.float32))
                target_len = P * DEMO_STRIDE
                if len(acts_10d) < target_len:
                    pad = np.zeros(
                        (target_len - len(acts_10d), ACTION_DIM_10D), dtype=np.float32
                    )
                    acts_10d = np.concatenate([acts_10d, pad], axis=0)
                else:
                    acts_10d = acts_10d[:target_len]
                demo_acts = torch.from_numpy(
                    acts_10d.reshape(1, P, DEMO_STRIDE, ACTION_DIM_10D)
                ).to(device=self.device, dtype=torch.float32)

                d_ori, d_pos, d_grip = self.policy._project_proprio_tokens(demo_prop)
                d_act_norm = self.policy.action_normalizer.normalize(demo_acts)
                d_act_tok = self.policy.action_proj(d_act_norm.reshape(1, P, -1))
                prompt_6 = torch.stack(
                    [
                        demo_rgb[None, :, 0, :],
                        demo_rgb[None, :, 1, :],
                        d_ori,
                        d_pos,
                        d_grip,
                        d_act_tok,
                    ],
                    dim=2,
                )
                M_d = self.policy.prompt_attention_pool(
                    prompt_6.reshape(P, 6, EMBED_DIM)
                ).reshape(1, P, EMBED_DIM)
                mem = M_d + self.policy.prompt_pos_emb[:, :P, :]
                mem = torch.cat([self.policy.attention_sink_tokens, mem], dim=1)
            else:
                max_p = self.policy.teacher.reference_reader.prompt_pos_emb.shape[1]
                if P > max_p:
                    demo_rgb = demo_rgb[:max_p]
                mem = self.policy.encode_demo_memory(demo_rgb[None])

        return mem[0].float().contiguous()

    @torch.inference_mode()
    def _preencode_all_prompts(self) -> None:
        amp_ctx = (
            torch.autocast(device_type=self.device.type, dtype=torch.bfloat16)
            if self.use_bf16
            else torch.autocast(device_type=self.device.type, enabled=False)
        )

        if self.prompt_mode == "default_paired":
            for ti, task in enumerate(self.tasks):
                h5_path = CHAIN_HDF5_DIR / f"{task}_demo.hdf5"
                with h5py.File(h5_path, "r") as f:
                    conv = str(f["data"].attrs.get("macros_image_convention", "opengl"))
                    for di in range(DEFAULT_PROMPT_SLOTS):
                        d = f[f"data/demo_{di}"]
                        self.prompt_memories[(ti, di)] = self._encode_single_demo_group(
                            d, conv, amp_ctx
                        )
        elif self.prompt_mode == "shifted":
            for ti, task in enumerate(self.tasks):
                h5_path = CHAIN_HDF5_DIR / f"{task}_demo.hdf5"
                with h5py.File(h5_path, "r") as f:
                    conv = str(f["data"].attrs.get("macros_image_convention", "opengl"))
                    for di in range(DEFAULT_PROMPT_SLOTS):
                        src_di = SHIFT_OFFSET + di
                        d = f[f"data/demo_{src_di}"]
                        self.prompt_memories[(ti, di)] = self._encode_single_demo_group(
                            d, conv, amp_ctx
                        )
        elif self.prompt_mode == "shuffle":
            n_tasks = len(self.tasks)
            for ti in range(n_tasks):
                donor_task = self.tasks[(ti + 1) % n_tasks]
                h5_path = CHAIN_HDF5_DIR / f"{donor_task}_demo.hdf5"
                with h5py.File(h5_path, "r") as f:
                    conv = str(f["data"].attrs.get("macros_image_convention", "opengl"))
                    for di in range(DEFAULT_PROMPT_SLOTS):
                        d = f[f"data/demo_{di}"]
                        self.prompt_memories[(ti, di)] = self._encode_single_demo_group(
                            d, conv, amp_ctx
                        )
        elif self.prompt_mode == "oracle_gt":
            for ti, task in enumerate(self.tasks):
                task_dir = ORACLE_GT_EXPERTS_DIR / task
                if not task_dir.is_dir():
                    continue
                for qi in range(50):
                    h5_path = task_dir / f"query_{qi:02d}" / "demo.hdf5"
                    if not h5_path.is_file():
                        continue
                    with h5py.File(h5_path, "r") as f:
                        conv = str(f["data"].attrs.get("macros_image_convention", "opengl"))
                        d = f["data/demo_0"]
                        self.prompt_memories[(ti, qi)] = self._encode_single_demo_group(
                            d, conv, amp_ctx
                        )

    @torch.inference_mode()
    def predict_batch(
        self,
        keys: List[Tuple[int, int]],
        seeds: List[int],
        rgb_batch: np.ndarray,
        proprio_batch: np.ndarray,
    ) -> np.ndarray:
        B = len(keys)
        dev = self.device

        av = rgb_batch[:, :, 0].reshape(B * 2, 128, 128, 3)
        eh = rgb_batch[:, :, 1].reshape(B * 2, 128, 128, 3)
        q_feats = self.visual.encode_dual_camera_uint8(
            av,
            eh,
            convention="opengl",
            batch_size=max(64, B * 2),
            autocast_dtype=torch.float16 if dev.type == "cuda" else None,
        ).reshape(B, 2, 2, EMBED_DIM)

        mems = [self.prompt_memories[k] for k in keys]
        max_m = max(m.shape[0] for m in mems)
        memory = torch.zeros((B, max_m, EMBED_DIM), device=dev, dtype=torch.float32)
        mem_mask = torch.ones((B, max_m), device=dev, dtype=torch.bool)
        for i, m in enumerate(mems):
            L = m.shape[0]
            memory[i, :L] = m
            mem_mask[i, :L] = False

        noises = []
        for s in seeds:
            gen = torch.Generator(device="cpu").manual_seed(int(s))
            noises.append(torch.randn((ACTION_HORIZON, ACTION_DIM_10D), generator=gen))
        init_noise = torch.stack(noises, dim=0).to(device=dev, dtype=torch.float32)

        amp_ctx = (
            torch.autocast(device_type=dev.type, dtype=torch.bfloat16)
            if self.use_bf16
            else torch.autocast(device_type=dev.type, enabled=False)
        )
        with amp_ctx:
            if self.mode in ("e5", "bpp_rgb_only"):
                assert isinstance(self.policy, E5Policy)
                h_q = self.policy.format_query_tokens(q_feats)
                rr = self.policy.reference_reader
                z_ref = rr.prompt_with_obs_decoder(
                    tgt=h_q + rr.prompt_current_obs_pos_emb,
                    memory=memory,
                    memory_key_padding_mask=mem_mask,
                )
                if self.policy.residual_transformer is not None:
                    z_cond = z_ref + self.policy.residual_transformer(z_ref, h_q)
                else:
                    z_cond = z_ref
                gcond = self.policy._build_global_cond(h_q, z_cond)
                action_10d = self.policy.sample_from_global_cond(gcond, init_noise=init_noise)
                exec_7d = extract_exec_actions(action_10d, exec_horizon=EXEC_HORIZON)
            elif self.mode == "bpp_full":
                assert isinstance(self.policy, BPPFullPolicy)
                q_prop = torch.from_numpy(proprio_batch).to(device=dev, dtype=torch.float32)
                q_ori, q_pos, q_grip = self.policy._project_proprio_tokens(q_prop)
                h_q = torch.stack(
                    [q_feats[:, :, 0], q_feats[:, :, 1], q_ori, q_pos, q_grip], dim=2
                ).reshape(B, FULL_QUERY_TOKENS, EMBED_DIM)
                z_ref = self.policy.prompt_with_obs_decoder(
                    tgt=h_q + self.policy.prompt_current_obs_pos_emb,
                    memory=memory,
                    memory_key_padding_mask=mem_mask,
                )
                gcond = torch.cat([h_q, z_ref], dim=1).reshape(B, -1)
                traj = init_noise.clone()
                self.policy.noise_scheduler.set_timesteps(
                    self.policy.num_inference_steps, device=dev
                )
                for t in self.policy.noise_scheduler.timesteps:
                    out = self.policy.action_decoder(
                        traj.to(dtype=gcond.dtype), t, local_cond=None, global_cond=gcond
                    ).float()
                    traj = self.policy.noise_scheduler.step(out, t, traj).prev_sample
                action_10d = self.policy.action_normalizer.unnormalize(traj)
                exec_7d = extract_exec_actions(action_10d, exec_horizon=EXEC_HORIZON)
            elif self.is_stage2_1:
                out = self.policy.predict_action_from_memory(
                    memory,
                    mem_mask,
                    q_feats,
                    apply_delta=self.apply_delta,
                    num_delta_steps=self.num_delta_steps,
                    delta_scale=self.delta_scale,
                    init_noise=init_noise,
                )
                exec_7d = out["exec_action_7d"]
            else:
                out = self.policy.predict_action_from_memory(
                    memory,
                    mem_mask,
                    q_feats,
                    apply_delta=self.apply_delta,
                    init_noise=init_noise,
                )
                exec_7d = out["exec_action_7d"]

        return np.ascontiguousarray(exec_7d.float().cpu().numpy(), dtype=np.float32)


class UnixBatchedServer:
    def __init__(
        self,
        engine: DemoSwapBatchedEngine,
        socket_path: Path,
        max_batch: int = 20,
        coalesce_ms: float = 4.0,
    ):
        self.engine = engine
        self.socket_path = Path(socket_path)
        self.max_batch = max_batch
        self.coalesce_s = coalesce_ms / 1000.0
        self.req_q: queue.Queue = queue.Queue()
        self.stop_event = threading.Event()
        self.stats = {"requests": 0, "batches": 0}

    def _client_thread(self, conn: socket.socket) -> None:
        try:
            while not self.stop_event.is_set():
                raw = _recv_exact(conn, REQ_TOTAL_BYTES)
                if raw is None:
                    break
                ti, di, seed, _flags = REQ_HDR.unpack_from(raw, 0)
                rgb = np.frombuffer(
                    raw, dtype=np.uint8, count=RGB_BYTES, offset=REQ_HDR.size
                ).reshape(RGB_SHAPE)
                prop = np.frombuffer(
                    raw,
                    dtype=np.float32,
                    count=PROPRIO_BYTES // 4,
                    offset=REQ_HDR.size + RGB_BYTES,
                ).reshape(PROPRIO_SHAPE)
                reply_q: queue.Queue = queue.Queue(maxsize=1)
                self.req_q.put(((ti, di), seed, rgb.copy(), prop.copy(), reply_q))
                resp = reply_q.get()
                if isinstance(resp, BaseException):
                    raise resp
                conn.sendall(resp)
        except (BrokenPipeError, ConnectionResetError, EOFError):
            pass
        finally:
            conn.close()

    def _batch_worker(self) -> None:
        while not self.stop_event.is_set():
            try:
                first = self.req_q.get(timeout=0.1)
            except queue.Empty:
                continue
            batch = [first]
            deadline = time.monotonic() + self.coalesce_s
            while len(batch) < self.max_batch:
                rem = deadline - time.monotonic()
                if rem <= 0:
                    break
                try:
                    batch.append(self.req_q.get(timeout=rem))
                except queue.Empty:
                    break

            keys = [item[0] for item in batch]
            seeds = [item[1] for item in batch]
            rgbs = np.stack([item[2] for item in batch], axis=0)
            props = np.stack([item[3] for item in batch], axis=0)
            try:
                actions = self.engine.predict_batch(keys, seeds, rgbs, props)
                self.stats["requests"] += len(batch)
                self.stats["batches"] += 1
                for i, item in enumerate(batch):
                    item[4].put(actions[i].tobytes())
            except BaseException as exc:
                for item in batch:
                    item[4].put(exc)

    def serve(self, ready_file: Optional[Path] = None) -> None:
        if self.socket_path.exists():
            self.socket_path.unlink()
        self.socket_path.parent.mkdir(parents=True, exist_ok=True)

        worker = threading.Thread(target=self._batch_worker, daemon=True)
        worker.start()

        srv = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        srv.bind(str(self.socket_path))
        srv.listen(64)
        srv.settimeout(0.5)

        def _handle_sig(_signum, _frame):
            self.stop_event.set()

        signal.signal(signal.SIGTERM, _handle_sig)
        signal.signal(signal.SIGINT, _handle_sig)

        if ready_file is not None:
            ready_file.parent.mkdir(parents=True, exist_ok=True)
            ready_file.write_text(f"pid={os.getpid()} socket={self.socket_path}\n")

        try:
            while not self.stop_event.is_set():
                try:
                    conn, _ = srv.accept()
                except socket.timeout:
                    continue
                t = threading.Thread(target=self._client_thread, args=(conn,), daemon=True)
                t.start()
        finally:
            self.stop_event.set()
            srv.close()
            if self.socket_path.exists():
                self.socket_path.unlink(missing_ok=True)
            print(
                f"[DemoSwapServer] Stopped after {self.stats['requests']} requests in "
                f"{self.stats['batches']} batches",
                flush=True,
            )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mode",
        choices=(
            "bpp_rgb_only",
            "e5",
            "bpp_full",
            "e6_stage2",
            "e6_stage2_no_delta",
            "e6_stage2_1",
            "e6_stage2_1_no_delta",
            "e6_stage2_1_2step",
        ),
        required=True,
    )
    parser.add_argument("--delta-steps", type=int, default=None)
    parser.add_argument("--delta-scale", type=float, default=1.0)
    parser.add_argument(
        "--prompt-mode",
        choices=("default_paired", "shifted", "oracle_gt", "shuffle"),
        required=True,
    )
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--stage1-ckpt", type=Path, default=DEFAULT_STAGE1_CKPT)
    parser.add_argument("--socket", type=Path, required=True)
    parser.add_argument("--ready-file", type=Path, default=None)
    parser.add_argument("--max-batch", type=int, default=20)
    parser.add_argument("--coalesce-ms", type=float, default=4.0)
    parser.add_argument("--no-bf16", action="store_true")
    args = parser.parse_args()

    device = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
    engine = DemoSwapBatchedEngine(
        mode=args.mode,
        prompt_mode=args.prompt_mode,
        checkpoint=args.checkpoint,
        stage1_ckpt=args.stage1_ckpt,
        device=device,
        use_bf16=not args.no_bf16,
        delta_steps=args.delta_steps,
        delta_scale=args.delta_scale,
    )
    server = UnixBatchedServer(
        engine=engine,
        socket_path=args.socket,
        max_batch=args.max_batch,
        coalesce_ms=args.coalesce_ms,
    )
    server.serve(ready_file=args.ready_file)


if __name__ == "__main__":
    main()
